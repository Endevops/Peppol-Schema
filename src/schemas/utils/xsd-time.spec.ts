import { describe, it, expect } from 'vitest';
import { xsdTime } from './xsd-time';

describe('xsdTime', () => {
  it.for([
    '00:00:00',
    '00:00:00Z',
    '00:00:00+01:00',
    '00:00:00-01:00',
    '00:00:00-0100',
    '00:00:00+0100',
    '10:12:45-05:30',
    '00:00:59+0100',
    '00:00:00.0Z',
    '00:00:00.00Z',
    '00:00:00.000000000Z',
    '00:00:00.000000000+01:00',
    '23:59:59',
    '23:59:59Z',
    '12:30:45.5',
    '12:30:45.123456789',
    '00:00:00+14:00',
    '00:00:00-14:00',
    '00:00:00+1400',
    '00:00:00-1400',
    '00:00:00+23:59',
    '00:00:00-23:59',
    '00:00:00+2359',
    '14:30:00Z',
    '14:30:00+00:00',
  ] as const)('should parse %s as iso date', val => {
    expect(() => xsdTime.parse(val)).not.toThrow();
  });

  it.for([
    '10:10:11-0000',
    '10:10:11-00',
    '24:10:11+0000',
    '00:60:11+0000',
    '00:00:60+0000',
    '00:00:00+2400',
    '00:00:00-2400',
    '00:00:00.Z',
    '25:00:00',
    '24:00:00',
    '24:00:00Z',
    '12:30:45.1234567890',
    '00:00:00+25:00',
    '00:00:00-25:00',
    '00:00:00+00:60',
    '00:00:00-00:60',
    '00:00:00+2600',
    '00:00:00-2600',
    '00:00:00+',
    '00:00:00-',
    '00:00:00+1',
    '00:00:00-1',
    '00:00:00.',
    '00:00',
    '00:00:',
    '',
  ] as const)('should not parse %s as iso date', val => {
    expect(() => xsdTime.parse(val)).toThrow();
  });
});
