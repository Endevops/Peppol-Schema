/**
 * @description The latest version of the document types.\
 * Since they release process is kinda scary, I keep it raw here and update manually.\
 * (They don't bother create any github release)
 */
const version = 'v9.7';

async function generateDocumentTypes(valuePath: string, publicationPath: string) {
  console.log(`Processing ${pc.blueBright('document types')}`);
  const sourceFileName = `Peppol Code Lists - Document types ${version}.json`;
  const generatedFileName = 'document-type.generated.ts';
  const variableName = 'documentTypes';
  const documentTypesContent = JSON.parse(await fs.readFile(path.join(publicationPath, sourceFileName), 'utf-8')) as {
    version: string;
    values: Array<Record<string, string>>;
  };

  const grouped = documentTypesContent.values.reduce<Record<string, Array<Record<string, string>>>>((prev, curr) => {
    (prev[curr['scheme']!] ??= []).push(curr);
    return prev;
  }, {});
  const tableKeys = Object.keys(grouped);

  await fs.writeFile(
    path.join(valuePath, generatedFileName),
    `// oxlint-disable
/// Do not edit this file directly. It is generated by \`scripts/values.ts\`

export const ${variableName}Table = {
${Object.entries(grouped)
  .map(([key, value]) => `  "${key}": [ ${value.map(v => `"${v['value']}"`).join(', ')} ]`)
  .join(',\n')}
};

${generateKeyDeclarations({ keys: tableKeys, keysName: `${variableName}TableKeys`, variableName: `${variableName}Table` })}

export const ${variableName}Scheme = [
${tableKeys.map(key => `  "${key}",`).join('\n')}
];


export const ${variableName}ProcessIds = {
${Object.entries(grouped)
  .map(([key, value]) => value.map(v => `"${key}::${v['value']}": ${JSON.stringify(v['process-ids'])}`).join(',\n'))
  .join(',\n')}
};

export const ${variableName}List = [
${Object.entries(grouped)
  .flatMap(([key, value]) => value.map(v => `"${key}::${v['value']}"`).join(',\n'))
  .join(',\n')}
];

/**
 * The list of elements that are deprecated.
 */
export const deprecated${String.capitalize(variableName)} = [
${documentTypesContent.values
  .filter(value => value['state'] !== 'active')
  .map(value => `  "${value['value']}",`)
  .join('\n')}
];
`
  );
}

async function generateParticipantIdentifierSchemes(valuePath: string, publicationPath: string) {
  console.log(`Processing ${pc.blueBright('participant identifier schemes')}`);

  const sourceFileName = `Peppol Code Lists - Participant identifier schemes ${version}.json`;
  const generatedFileName = 'participant-identifier-schemes.generated.ts';
  const variableName = 'participantIdentifierSchemes';
  const documentTypesContent = JSON.parse(await fs.readFile(path.join(publicationPath, sourceFileName), 'utf-8')) as {
    version: string;
    values: Array<Record<string, string | undefined>>;
  };
  const keys = documentTypesContent.values.map(value => value['iso6523']).filter((value): value is string => Boolean(value));

  await fs.writeFile(
    path.join(valuePath, generatedFileName),
    `// oxlint-disable
/// Do not edit this file directly. It is generated by \`scripts/values.ts\`

/**
 * @title Peppol Participant Identifier Schemes
 * @version ${documentTypesContent.version}
 * @enum
 * @category Peppol Values
 */
export const ${variableName} = {
${documentTypesContent.values
  .map(value => {
    const examples = value['examples']
      ? `\n* @example \n* ${value['examples']
          ?.split('\n')
          .map(ex => `\`${ex.trim()}\``)
          .join('\n* ')}`
      : '';

    const validations = value['validation-rules']
      ? `\n* @validation \n* ${value['validation-rules']
          .split('\n')
          .map(rule => {
            const r = rule.trim();
            if (r.startsWith('RegEx: ')) {
              return `\`\`\`regex\n* ${r.slice(7)}\n* \`\`\``;
            }
            return r;
          })
          .join('\n* ')}`
      : '';

    return `/**
* @name \`${value['scheme-name']?.replace('\n', ' ')}\`
* @country \`${value['country']}\`
* @since ${value['initial-release']}${value['state'] !== 'active' ? '\n* @deprecated' : ''}${examples}${validations}
*/
"${value['iso6523']}": "${value['schemeid']}",`;
  })
  .join('\n')}
};

${generateKeyDeclarations({ keys, keysName: `${variableName}Keys`, variableName: variableName })}

export const ${variableName}Validations = {
${documentTypesContent.values
  .map(value => {
    const validations = value['validation-rules']
      ? value['validation-rules']
          .split('\n')
          .filter(rule => rule.trim().startsWith('RegEx: '))
          .map(rule => {
            const r = rule.trim();
            return `/${r.slice(7)}/g`;
          })
          .join(', ')
      : '';

    return `"${value['iso6523']}": ${String.isEmpty(validations) ? 'undefined' : `[${validations}]`},`;
  })
  .join('\n')}
}

/**
 * The list of elements that are deprecated.
 */
export const deprecated${String.capitalize(variableName)} = [
${documentTypesContent.values
  .filter(value => value['state'] !== 'active')
  .map(value => `  "${value['iso6523']}",`)
  .join('\n')}
];
`
  );
}

