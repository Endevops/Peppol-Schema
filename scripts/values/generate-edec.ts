export async function generateEdec(valuePath: string) {
  await using edecTempDir = await fs.mkdtempDisposable('/tmp/edec-XXXXXX');

  const edecRepo = 'https://github.com/OpenPEPPOL/edec-codelists.git';
  console.log(`Cloning edec code list (${pc.dim(edecRepo)}) repository to ${pc.yellow(edecTempDir.path)}`);
  await Git.clone(edecRepo, edecTempDir.path, { '--depth': 1 });

  console.log('Creating value folder at', pc.yellow(valuePath));
  await fs.mkdir(valuePath, { recursive: true });

  console.log(pc.green('--- Starting to process edec values files ---'));
  const publicationPath = path.join(edecTempDir.path, 'publication', version);

  // const generationList = [
  //   [`Peppol Code Lists - SPIS Use Case ${version}.json`, 'spi-use-cases.generated.ts', 'spiUseCases'],
  //   [`Peppol Code Lists - Transport profiles ${version}.json`, 'spi-use-cases.generated.ts', 'spiUseCases'],
  // ];

  await generateDocumentTypes(valuePath, publicationPath);
  await generateParticipantIdentifierSchemes(valuePath, publicationPath);
  await generateProcess(valuePath, publicationPath);

  console.log(pc.green('--- All edec value files processed ---'));
}
