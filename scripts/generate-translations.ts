#!/usr/bin/env node
// fallow-ignore-file security-sink
// Offline CLI script: destination path is provided by the developer invoking it,
// so filesystem targets are operator-controlled, not untrusted input.
import { NodeRuntime, NodeServices } from '@effect/platform-node';
import { Console, Effect, FileSystem, Path, Schema, Stream, String } from 'effect';
import { Argument, Command } from 'effect/cli';
import pc from 'picocolors';

const typescript = String.String.raw;

// oxlint-disable-next-line import/no-relative-parent-imports
const translations = (await import('../assets/translations.json', { with: { type: 'json' } })).default;
// oxlint-disable-next-line import/no-relative-parent-imports
const pkg = (await import('../package.json', { with: { type: 'json' } })).default;

const ignored: Array<string> = [
  'countryCodes',
  'currencyCodes',
  'additionalDocumentReferenceCodes',
  'quantityUnitCodes',
  'electronicAddressCodes',
  'icdCodes',
  'documentTypeCodes',
];

/**
 * @description A single translated term: the paraglide message identifiers for the label and its description.
 */
const Translation = Schema.Struct({ description: Schema.String, text: Schema.String });

/**
 * @description `assets/translations.json` is a map of code list -> code -> translation.
 */
const Translations = Schema.Record(Schema.String, Schema.Record(Schema.String, Translation));

/**
 * @description One generated file, ready to be written to disk.
 */
const TranslationFile = Schema.Struct({ content: Schema.String, destination: Schema.String });

/**
 * @description Raised when the translations asset does not match the expected shape.
 */
class TranslationsDecodeError extends Schema.TaggedError<TranslationsDecodeError>()('TranslationsDecodeError', { message: Schema.String }) {}

const renderTranslationFile = (file: string, value: (typeof Translations)['Type'][string]): string => {
  const translationVariable = `${file}Translations`;

  return typescript`
// oxlint-disable
/// Do not edit this file directly.
import { m } from '~/paraglide/messages';

export const ${translationVariable}: Record<string, { text: m.LocalizedString; description: m.LocalizedString }>  = {
${Object.entries(value)
  .map(
    ([key, { text, description }]) => `get ["${key}"]() {
    return {
      text: m.${text}(),
      description: m.${description}(),
    }
  }`
  )
  .join(',\n')}
};`;
};

/**
 * @description Validates the JSON asset once, before any file is generated.
 */
const decodeTranslations = Effect.fnUntraced(function* () {
  return yield* Schema.decodeEffect(Translations)(translations).pipe(
    Effect.mapError(error => new TranslationsDecodeError({ message: error.message }))
  );
});

const renderFiles = Effect.fnUntraced(function* (destination: string) {
  const path = yield* Path.Path;
  const decoded = yield* decodeTranslations();

  return Object.entries(decoded)
    .filter(([file]) => !ignored.includes(file))
    .map(([file, value]) => {
      const filename = String.kebabCase(String.capitalize(file));
      return {
        content: renderTranslationFile(file, value),
        destination: path.join(destination, `${filename}.translations.ts`),
      } satisfies typeof TranslationFile.Type;
    });
});

const writeFile = Effect.fn('generateTranslations.writeFile')(function* (file: typeof TranslationFile.Type) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const relative = path.relative(process.cwd(), file.destination);

  yield* Console.log('Writing', pc.yellow(relative));
  yield* fs.writeFileString(file.destination, file.content);
  yield* Console.log('Wrote  ', pc.yellow(relative));
});

const command = Command.make(
  'generate-translations',
  {
    destination: Argument.Directory('destination').pipe(
      Argument.withDescription('Directory where the generated *.translations.ts files are written')
    ),
  },
  ({ destination }) =>
    Effect.gen(function* () {
      const fs = yield* FileSystem.FileSystem;

      yield* fs.makeDirectory(destination, { recursive: true });
      yield* Console.debug(pc.dim(`Generating translations into ${pc.yellow(destination)}`));

      const files = yield* renderFiles(destination);

      yield* Stream.fromIterable(files).pipe(Stream.mapEffect(writeFile, { concurrency: 8 }), Stream.runDrain);
    })
);

Command.run(command, { version: pkg.version }).pipe(Effect.provide(NodeServices.layer), NodeRuntime.runMain);
